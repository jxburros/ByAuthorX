"""The ByAuthorX promo film: nine Vixl timeline scenes, a synthesized score, one MP4.

Scenes are ordinary Vixl documents (`docs/promo/scenes/*.vixl`). Every box, arrow, ring and rule is
a seeded hand-inked stroke from the same drawing kit as the visual guides (scripts/build_visual_guides.py),
with a stronger wobble, and strokes write themselves on with `trim_end`. The product shots are the
screenshots in docs/images. Nothing is generated by a model.

    python -m venv .venv-assets
    .venv-assets/bin/python -m pip install -r assets/brand-fonts/requirements.txt
    .venv-assets/bin/python scripts/build_promo_video.py [--draft] [--only SCENE] [--stills]

`--stills` writes a contact sheet per scene for review, `--draft` renders a small, fast film.
"""

