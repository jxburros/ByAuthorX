IPTC = 'http://cv.iptc.org/newscodes/digitalsourcetype/'


def developer(model: str, provider_kind: str | None = None) -> str | None:
    name = (model or '').casefold().split('/')[-1]
    for prefix, company in DEVELOPERS:
        if name.startswith(prefix):
            return company
    return PROVIDER_DEVELOPERS.get(provider_kind or '')


def _day(value: str | None, fallback: date) -> date:
    try:
        return datetime.fromisoformat(value).date() if value else fallback
    except ValueError:
        return fallback


def _join(items: list[str]) -> str:
    if len(items) <= 2:
        return ' and '.join(items)
    return ', '.join(items[:-1]) + ', and ' + items[-1]


def basis(doc: dict[str, Any], target: str | None = None, *, today: date | None = None) -> dict[str, Any]:
    """What a disclosure states: tools (model, developer, last use), shares and tasks."""
    report = provenance.report(doc, target, limit=100000)
    today = today or datetime.now(UTC).date()
    tools: dict[tuple[str, str], dict[str, Any]] = {}
    tasks: set[str] = set()
    edited = False
    claims_by_record: dict[str, int] = {}
    for claim in report['claims']:
        claims_by_record[claim['record']] = claims_by_record.get(claim['record'], 0) + 1
        edited = edited or claim['state'] == 'edited'
        if any(g.get('citation_id') for g in claim['grounding']):
            tasks.add('citing')
    for record in report['records'].values():
        if record['origin'] not in provenance.AI_ORIGINS:
            continue
        model = record.get('model') or record.get('provider') or '[AI tool]'
        key = (model, record.get('provider', ''))
        company = developer(model, record.get('provider_kind'))
        entry = tools.setdefault(
            key,
            {
                'model': model,
                'provider': record.get('provider', ''),
                'developer': company,
                'first': None,
                'last': None,
            },
        )
        used = _day(record.get('created'), today)
        entry['first'] = min(filter(None, (entry['first'], used)))
        entry['last'] = max(filter(None, (entry['last'], used)))
        if record.get('task'):
            tasks.add(record['task'])
        edited = edited or bool(record.get('edited_by_human'))
    shares = report['percentages']
    return {
        'scope': report['scope'],
        'tools': [
            {**t, 'first': t['first'].isoformat(), 'last': t['last'].isoformat()}
            for t in sorted(tools.values(), key=lambda t: (t['developer'] or '', t['model']))
        ],
        'tasks': [t for t in provenance.TASKS if t in tasks],
        'percentages': shares,
        'ai_share': round(shares['ai_generated'] + shares['ai_edited'], 1),
        'edited_by_author': edited,
        'characters': report['characters'],
        'claims': len(report['claims']),
        'recording': report['recording'],
    }


def _apa(info):
    tools, references, needs = [], [], []
    for tool in info['tools']:
        year = tool['last'][:4]
        company = tool['developer'] or '[Developer]'
        if not tool['developer']:
            needs.append(f'the developer of {tool["model"]}')
        tools.append(f'{tool["model"]} ({company}, {year})')
        url = DEVELOPER_URLS.get(tool['developer'] or '', '')
        prefix = f'{company}. ({year}). '
        title = tool['model']
        tail = ' [Large language model].' + (f' {url}' if url else '')
        references.append({'text': prefix + title + tail, 'italic': [len(prefix), len(prefix) + len(title)]})
    shares = info['percentages']
    tasks = _join([TASK_PHRASES[t] for t in info['tasks']]) or 'writing assistance'
    text = (
        f'I used {_join(tools)}, a generative artificial intelligence (AI) tool'
        + ('s' if len(tools) > 1 else '')
        + f', for {tasks}. '
        + _shares_sentence(shares)
        + ' I reviewed and revised the AI output and take responsibility for the final text.'
    )
    return (
        text,
        references,
        needs,
        'In the Method section, the author note or another place your instructor or publisher names.',
    )


def _shares_sentence(shares):
    parts = []
    if shares['ai_generated']:
        parts.append(f'about {shares["ai_generated"]}% of the text was generated by AI')
    if shares['ai_edited']:
        parts.append(f'about {shares["ai_edited"]}% was edited by AI')
    if shares['human']:
        parts.append(f'{shares["human"]}% was typed by me')
    if shares['pasted']:
        parts.append(f'{shares["pasted"]}% was pasted from other sources')
    if shares['unrecorded']:
        parts.append(f'{shares["unrecorded"]}% has no recorded origin')
    sentence = _join(parts) or 'no AI-written text remains in this document'
    return 'According to the document’s provenance log, ' + sentence + '.'


def _mla(info):
    tools, references, needs = [], [], []
    for tool in info['tools']:
        company = tool['developer'] or '[Developer]'
        if not tool['developer']:
            needs.append(f'the developer of {tool["model"]}')
        product = PRODUCTS.get(tool['developer'] or '', tool['model'])
        tools.append(f'{product}, model {tool["model"]} ({company})')
        day = date.fromisoformat(tool['last'])
        when = f'{day.day} {MLA_MONTHS[day.month - 1]} {day.year}'
        description = (
            '“' + (_join([TASK_PHRASES[t] for t in info['tasks']]) or 'writing assistance').capitalize()
        )
        description += ' for this document” prompt. '
        url = DEVELOPER_URLS.get(tool['developer'] or '', '[shareable URL]')
        references.append(
            {
                'text': f'{description}{product}, model {tool["model"]}, {company}, {when}, {url}.',
                'italic': [len(description), len(description) + len(product)],
            }
        )
    tasks = _join([TASK_PHRASES[t] for t in info['tasks']]) or 'writing assistance'
    text = (
        f'Acknowledgment of AI use: I used {_join(tools)} for {tasks}. '
        + _shares_sentence(info['percentages'])
        + ' Where AI pointed to sources, I consulted and cite the sources directly.'
    )
    return (
        text,
        references,
        needs,
        'In a note or acknowledgment, with works-cited entries for quoted or paraphrased output.',
    )


def _named(tool):
    product = PRODUCTS.get(tool['developer'] or '')
    return (
        f'{product} ({tool["model"]})'
        if product and product.casefold() not in tool['model'].casefold()
        else tool['model']
    )


def _chicago(info):
    notes, needs = [], []
    edited = ', edited for style and content' if info['edited_by_author'] else ''
    for index, tool in enumerate(info['tools'], 1):
        company = tool['developer'] or '[Developer]'
        if not tool['developer']:
            needs.append(f'the developer of {tool["model"]}')
        day = date.fromisoformat(tool['last'])
        when = f'{MONTHS[day.month - 1]} {day.day}, {day.year}'
        notes.append(
            {
                'text': f'{index}. Text generated by {_named(tool)}, {company}, {when}{edited}.',
                'italic': None,
            }
        )
    names = _join([_named(t) for t in info['tools']])
    tasks = _join([TASK_PHRASES[t] for t in info['tasks']]) or 'writing assistance'
    text = f'Parts of this text were generated or edited with {names} for {tasks}. ' + _shares_sentence(
        info['percentages']
    )
    return text, notes, needs, 'In the text, or in a numbered footnote or endnote for formal work.'


def disclose(
    doc: dict[str, Any], style: str = 'apa', *, target: str | None = None, today: date | None = None
) -> dict[str, Any]:
    """An AI-use disclosure in ``style`` (apa, mla or chicago) from the provenance log."""
    style = (style or 'apa').casefold()
    if style not in STYLES:
        raise ByaxError('invalid_input', 'Disclosure style must be apa, mla or chicago.', field='style')
    info = basis(doc, target, today=today)
    guidance = dict(GUIDANCE[style])
    if not info['tools']:
        return {
            'style': style,
            'text': 'No AI-generated or AI-edited text is recorded in this document’s provenance log.',
            'references': [],
            'placement': None,
            'needs_review': []
            if info['recording'] == 'on'
            else ['Provenance recording is turned off for this document.'],
            'basis': info,
            'guidance': guidance,
            'ai_used': False,
        }
    text, references, needs, placement = {'apa': _apa, 'mla': _mla, 'chicago': _chicago}[style](info)
    if info['percentages']['unrecorded']:
        needs.append('part of the text has no recorded origin; check and describe it yourself')
    return {
        'style': style,
        'text': text,
        'references': references,
        'placement': placement,
        'needs_review': needs,
        'basis': info,
        'guidance': guidance,
        'ai_used': True,
        'note': 'Check your instructor’s or publisher’s policy; this statement is a starting point you edit.',
    }


def disclosure_proposal(
    doc: dict[str, Any], style: str = 'apa', *, after: str | None = None, target: str | None = None
) -> dict[str, Any]:
    """A ``propose`` operation inserting the statement (and references) after block ``after``."""
    result = disclose(doc, style, target=target)
    if after is None:
        after = doc['blocks'][-1]['id'] if doc.get('blocks') else None
    seed = hashlib.sha256(canonical_json([doc['revision'], style, result['text']]).encode()).hexdigest()[:16]
    operations: list[dict[str, Any]] = []
    previous = after
    for index, (text, italic) in enumerate(
        [(result['text'], None)] + [(r['text'], r.get('italic')) for r in result['references']]
    ):
        identity = f'p_disclosure_{seed}_{index}'
        operation: dict[str, Any] = {'type': 'insert_paragraph', 'text': text, 'id': identity}
        if previous is not None:
            operation['after'] = previous
        operations.append(operation)
        if italic:
            operations.append(
                {
                    'type': 'format_text',
                    'target': identity,
                    'start': italic[0],
                    'end': italic[1],
                    'marks': {'italic': True},
                }
            )
        previous = identity
    return {
        'type': 'propose',
        'values': {
            'operations': operations,
            'explanation': f'Insert the {style.upper() if style != "chicago" else "Chicago"} AI-use disclosure.',
            'author': 'ByAuthorX',
            'origin': 'disclosure',
        },
    }


# --- C2PA sidecar manifest ------------------------------------------------------------------------


def text_binding(doc: dict[str, Any]) -> dict[str, Any]:
    """SHA-256 of the body text, NFC-normalized and UTF-8 encoded (as C2PA 2.3 A.7 hashes text)."""
    text = unicodedata.normalize('NFC', text_of(doc))
    return {
        'alg': 'sha256',
        'hash': base64.b64encode(hashlib.sha256(text.encode('utf-8')).digest()).decode('ascii'),
        'normalization': 'NFC',
        'encoding': 'UTF-8',
        'scope': 'plain text of the document body (blocks joined by line feeds)',
    }


def c2pa_manifest(doc: dict[str, Any], *, title: str | None = None) -> dict[str, Any]:
    """An unsigned, informational C2PA-style manifest definition for the document's text."""
    from . import __version__

    info = basis(doc)
    shares = info['percentages']
    if info['ai_share'] >= 99.9:
        source_type = IPTC + 'trainedAlgorithmicMedia'
    elif info['ai_share'] > 0:
        source_type = IPTC + 'compositeWithTrainedAlgorithmicMedia'
    else:
        source_type = IPTC + 'digitalArt'
    agent = {'name': 'ByAuthorX', 'version': __version__}
    actions: list[dict[str, Any]] = [
        {
            'action': 'c2pa.created',
            'digitalSourceType': source_type,
            'softwareAgent': agent,
            'description': 'Text written in ByAuthorX; origins from the local provenance log.',
        }
    ]
    for tool in info['tools']:
        actions.append(
            {
                'action': 'c2pa.edited',
                'digitalSourceType': IPTC + 'trainedAlgorithmicMedia',
                'softwareAgent': {
                    'name': tool['model'],
                    **({'developer': tool['developer']} if tool['developer'] else {}),
                },
                'description': 'AI-generated or AI-edited text accepted through review ('
                + (', '.join(info['tasks']) or 'writing assistance')
                + ').',
                'when': tool['last'],
            }
        )
    metadata = doc.get('metadata', {})
    work: dict[str, Any] = {
        '@context': 'https://schema.org',
        '@type': 'CreativeWork',
        'name': title or metadata.get('title') or '',
    }
    if metadata.get('author'):
        work['author'] = [{'@type': 'Person', 'name': metadata['author']}]
    return {
        'claim_generator_info': [agent],
        'title': title or metadata.get('title') or '',
        'format': 'text/plain',
        'assertions': [
            {'label': 'c2pa.actions.v2', 'data': {'actions': actions}},
            {'label': 'stds.schema-org.CreativeWork', 'data': work},
            {
                'label': 'org.byauthorx.provenance.v1',
                'data': {
                    'percentages': shares,
                    'ai_share': info['ai_share'],
                    'tools': info['tools'],
                    'tasks': info['tasks'],
                    'characters': info['characters'],
                    'ai_claims': info['claims'],
                },
            },
            {'label': 'org.byauthorx.text-binding.v1', 'data': text_binding(doc)},
        ],
        'org.byauthorx.status': {
            'signed': False,
            'informational': True,
            'specification': 'C2PA 2.x assertions; not a signed C2PA manifest store',
            'note': 'An unsigned manifest is informational only: anyone can write one. Sign it with a C2PA tool '
            'and your own certificate to produce Content Credentials.',
        },
    }


def _sign(manifest: dict[str, Any], key_file: str | os.PathLike[str]) -> dict[str, Any]:
    try:
        from cryptography.hazmat.primitives import serialization
        from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
    except ImportError as exc:
        raise ByaxError(
            'missing_dependency',
            'Signing needs the optional "cryptography" package; the manifest was not written.',
        ) from exc
    try:
        key = serialization.load_pem_private_key(Path(key_file).read_bytes(), password=None)
    except (OSError, ValueError, TypeError) as exc:
        raise ByaxError(
            'invalid_input', 'The signing key could not be read as an unencrypted PEM key.', field='key_file'
        ) from exc
    if not isinstance(key, Ed25519PrivateKey):
        raise ByaxError('invalid_input', 'Only Ed25519 signing keys are supported.', field='key_file')
    signed = copy.deepcopy(manifest)
    signed['org.byauthorx.status'].update(
        signed=True,
        note='Detached Ed25519 signature over the canonical JSON of this file without the signature. It shows '
        'who produced the file; it is not a C2PA claim signature.',
    )
    payload = canonical_json(signed).encode()
    public = key.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    signed['org.byauthorx.signature'] = {
        'alg': 'Ed25519',
        'public_key': base64.b64encode(public).decode('ascii'),
        'value': base64.b64encode(key.sign(payload)).decode('ascii'),
        'payload': 'canonical JSON (sorted keys, no whitespace) of the manifest without org.byauthorx.signature',
    }
    return signed


def export_c2pa(
    doc: dict[str, Any],
    out: str | os.PathLike[str],
    *,
    key_file: str | os.PathLike[str] | None = None,
    overwrite: bool = False,
) -> dict[str, Any]:
    """Write the sidecar manifest to ``out`` (``.c2pa.json`` suggested); signed only with ``key_file``."""
    target = Path(out)
    if target.exists() and not overwrite:
        raise ByaxError('conflict', 'Output already exists; explicitly select overwrite', target=str(target))
    manifest = c2pa_manifest(doc)
    if key_file:
        manifest = _sign(manifest, key_file)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True) + '\n', encoding='utf-8'
    )
    return {'path': str(target), 'signed': bool(key_file), 'manifest': manifest}
