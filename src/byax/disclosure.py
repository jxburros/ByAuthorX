"""AI-use disclosure statements and an optional C2PA manifest, generated from the provenance log.

Context engine plan section 10. :func:`disclose` writes an APA, MLA or Chicago statement from
:func:`byax.provenance.report`: which tools and models were used, what share of the text they wrote
or edited, and for which tasks (drafting, editing, summarizing, citing, translating; derived from
the kinds of the accepted AI proposals). The formats follow the publishers' current guidance,
recorded in ``docs/user-guide.md`` ("Provenance and disclosure"):

- APA Style, "Citing generative AI in APA Style: Part 1—Reference formats" (2025): describe the use
  in the text (for example the Method section or author note) with an in-text citation such as
  "(OpenAI, 2025)", and list the tool as ``Company. (year). *Tool/Model* [Large language model]. URL``.
- MLA Style Center, "How do I cite generative AI in MLA style? (Updated and Revised)" and "Beyond
  Citation: Describing AI Use in Your Work" (13 August 2025): acknowledge substantive use in prose;
  works-cited entries are ``"Description" prompt. Tool, model Name, Company, Day Mon. Year, URL.``
- The Chicago Manual of Style Online, Q&A "Citation, Documentation of Sources" on AI (18th ed.):
  name the tool in the text or in a note such as ``1. Text generated by Tool, Company, Month Day,
  Year.``, adding "edited for style and content" when the writer edited the output.

The statement is text the writer copies or inserts through a review proposal
(:func:`disclosure_proposal`); nothing is inserted automatically. Placeholders in square brackets
mark what the log cannot know (a chat's share URL, an unknown developer).

:func:`c2pa_manifest` builds an *informational*, unsigned C2PA-style manifest definition for a
sidecar ``<name>.c2pa.json`` (C2PA 2.x assertions: ``c2pa.actions.v2`` with IPTC digital source
types, a schema.org ``CreativeWork`` and a ByAuthorX provenance summary bound to the text by
SHA-256). C2PA 2.3 (appendix A.7) defines embedding a *signed* JUMBF manifest store in unstructured
text with Unicode variation selectors; producing that needs a C2PA SDK and an X.509 signing
certificate, which ByAuthorX does not bundle. The sidecar is a manifest definition such tools can
sign. With a user-supplied Ed25519 key (and the optional ``cryptography`` package) the sidecar gets
a detached signature, which proves only that the key holder produced the file; it is not a C2PA
claim signature.
"""

