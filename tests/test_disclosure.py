"""AI-use disclosures (APA, MLA, Chicago snapshots) and the optional C2PA sidecar manifest."""

import base64
import hashlib
import json
import unicodedata
from datetime import date

import pytest

from byax import disclosure, engine
from byax.cli import execute
from byax.errors import ByaxError
from byax.model import canonical_json, new_document, text_of

TODAY = date(2026, 10, 16)


def _essay(model='claude-sonnet-4-5', kind='anthropic', rewrite=False):
    doc = new_document('Essay', 'Intro written by me.')
    doc['metadata']['author'] = 'A. Writer'
    b = doc['blocks'][0]['id']
    doc, _ = engine.apply(
        doc,
        {
            'operations': [{'type': 'insert_text', 'target': b, 'offset': 0, 'text': 'Typed. '}],
            'provenance': {'origin': 'human'},
        },
    )
    if rewrite:
        operation = {
            'type': 'replace_text',
            'target': b,
            'match': 'Intro',
            'replacement': 'Opening',
            'expected_text': 'Intro',
        }
    else:
        operation = {
            'type': 'insert_text',
            'target': b,
            'offset': len(doc['blocks'][0]['text']),
            'text': ' A drafted sentence.',
        }
    proposal = {
        'operations': [operation],
        'provenance': {'provider': 'work', 'model': model, 'provider_kind': kind},
    }
    doc, _ = engine.apply(doc, {'operations': [{'type': 'propose', 'values': proposal}]})
    doc, _ = engine.apply(
        doc,
        {
            'operations': [{'type': 'accept_proposal', 'target': doc['review']['proposals'][-1]['id']}],
            'provenance': {'origin': 'human'},
        },
    )
    for record in doc['provenance']['records'].values():
        record['created'] = '2026-10-12T09:30:00+00:00'
    return doc


SHARES = (
    'According to the document’s provenance log, about 42.6% of the text was generated by AI, 14.9% was '
    'typed by me, and 42.6% has no recorded origin.'
)


def test_apa_statement_and_reference_snapshot():
    result = disclosure.disclose(_essay(), 'apa', today=TODAY)
    assert result['text'] == (
        'I used claude-sonnet-4-5 (Anthropic, 2026), a generative artificial intelligence (AI) tool, for '
        'drafting text. '
        + SHARES
        + ' I reviewed and revised the AI output and take responsibility for the final text.'
    )
    (reference,) = result['references']
    assert (
        reference['text']
        == 'Anthropic. (2026). claude-sonnet-4-5 [Large language model]. https://www.anthropic.com/claude'
    )
    assert reference['text'][slice(*reference['italic'])] == 'claude-sonnet-4-5'
    assert result['guidance']['url'] == 'https://apastyle.apa.org/blog/cite-generative-ai-references'
    assert result['needs_review'] == [
        'part of the text has no recorded origin; check and describe it yourself'
    ]


def test_mla_acknowledgment_and_works_cited_snapshot():
    result = disclosure.disclose(_essay(), 'mla', today=TODAY)
    assert result['text'] == (
        'Acknowledgment of AI use: I used Claude, model claude-sonnet-4-5 (Anthropic) for drafting text. '
        + SHARES
        + ' Where AI pointed to sources, I consulted and cite the sources directly.'
    )
    (entry,) = result['references']
    assert entry['text'] == (
        '“Drafting text for this document” prompt. Claude, model claude-sonnet-4-5, Anthropic, 12 Oct. 2026, '
        'https://www.anthropic.com/claude.'
    )
    assert entry['text'][slice(*entry['italic'])] == 'Claude'


def test_chicago_note_snapshot_says_when_the_author_edited_ai_text():
    doc = _essay(model='gpt-4o', kind='openai')
    result = disclosure.disclose(doc, 'chicago', today=TODAY)
    assert (
        result['text']
        == 'Parts of this text were generated or edited with gpt-4o for drafting text. ' + SHARES
    )
    assert [n['text'] for n in result['references']] == [
        '1. Text generated by gpt-4o, OpenAI, October 12, 2026.'
    ]
    b = doc['blocks'][0]['id']
    position = doc['blocks'][0]['text'].index('drafted')
    edited, _ = engine.apply(
        doc,
        {
            'operations': [{'type': 'insert_text', 'target': b, 'offset': position, 'text': 'carefully '}],
            'provenance': {'origin': 'human'},
        },
    )
    note = disclosure.disclose(edited, 'chicago', today=TODAY)['references'][0]['text']
    assert note.endswith(', edited for style and content.')


def test_tasks_come_from_proposal_kinds_and_unknown_developers_are_flagged():
    result = disclosure.disclose(_essay(model='mystery-7b', kind='ollama', rewrite=True), 'apa', today=TODAY)
    assert result['basis']['tasks'] == ['editing']
    assert '[Developer]' in result['text'] and 'the developer of mystery-7b' in result['needs_review']
    assert 'editing and revising text' in result['text']


def test_no_ai_text_gives_an_honest_statement_and_bad_style_is_refused():
    result = disclosure.disclose(new_document('Plain', 'Only me.'), 'mla')
    assert result['ai_used'] is False and 'No AI-generated' in result['text']
    with pytest.raises(ByaxError):
        disclosure.disclose(new_document('x'), 'ieee')


def test_disclosure_is_inserted_only_through_a_review_proposal():
    doc = _essay()
    operation = disclosure.disclosure_proposal(doc, 'apa')
    proposed, _ = engine.apply(doc, {'operations': [operation]})
    assert proposed['blocks'] == doc['blocks']
    proposal = proposed['review']['proposals'][-1]
    accepted, _ = engine.apply(
        proposed, {'operations': [{'type': 'accept_proposal', 'target': proposal['id']}]}
    )
    inserted = [b for b in accepted['blocks'] if b['id'].startswith('p_disclosure_')]
    assert inserted[0]['text'].startswith('I used claude-sonnet-4-5')
    assert inserted[1]['marks'][0]['type'] == 'italic'


def test_c2pa_manifest_is_unsigned_informational_and_bound_to_the_text(tmp_path):
    doc = _essay()
    manifest = disclosure.c2pa_manifest(doc)
    labels = [a['label'] for a in manifest['assertions']]
    assert labels == [
        'c2pa.actions.v2',
        'stds.schema-org.CreativeWork',
        'org.byauthorx.provenance.v1',
        'org.byauthorx.text-binding.v1',
    ]
    actions = manifest['assertions'][0]['data']['actions']
    assert actions[0]['action'] == 'c2pa.created'
    assert actions[0]['digitalSourceType'].endswith('compositeWithTrainedAlgorithmicMedia')
    assert actions[1]['softwareAgent'] == {'name': 'claude-sonnet-4-5', 'developer': 'Anthropic'}
    binding = manifest['assertions'][3]['data']
    expected = hashlib.sha256(unicodedata.normalize('NFC', text_of(doc)).encode()).digest()
    assert base64.b64decode(binding['hash']) == expected
    assert (
        manifest['org.byauthorx.status']['signed'] is False
        and manifest['org.byauthorx.status']['informational']
    )
    out = tmp_path / 'essay.c2pa.json'
    written = disclosure.export_c2pa(doc, out)
    assert json.loads(out.read_text(encoding='utf-8')) == manifest and written['signed'] is False
    with pytest.raises(ByaxError):
        disclosure.export_c2pa(doc, out)


def test_c2pa_sidecar_is_signed_only_with_a_supplied_key(tmp_path):
    crypto = pytest.importorskip('cryptography.hazmat.primitives.asymmetric.ed25519')
    from cryptography.hazmat.primitives import serialization

    key = crypto.Ed25519PrivateKey.generate()
    pem = tmp_path / 'key.pem'
    pem.write_bytes(
        key.private_bytes(
            serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()
        )
    )
    written = disclosure.export_c2pa(_essay(), tmp_path / 'signed.c2pa.json', key_file=pem)
    manifest = written['manifest']
    signature = manifest.pop('org.byauthorx.signature')
    assert manifest['org.byauthorx.status']['signed'] is True
    key.public_key().verify(base64.b64decode(signature['value']), canonical_json(manifest).encode())
    pem.write_text('not a key')
    with pytest.raises(ByaxError):
        disclosure.export_c2pa(_essay(), tmp_path / 'bad.c2pa.json', key_file=pem)


def test_cli_disclose_and_export(tmp_path):
    path = str(tmp_path / 'essay.byax')
    from byax import storage

    storage.save_document(_essay(), path)
    result = execute('provenance', {'path': path, 'action': 'disclose', 'style': 'chicago'})
    assert result['disclosure']['style'] == 'chicago'
    out = str(tmp_path / 'essay.c2pa.json')
    exported = execute('provenance', {'path': path, 'action': 'export-c2pa', 'out': out})
    assert exported['outputs'] == [out] and exported['c2pa']['signed'] is False
    proposed = execute('provenance', {'path': path, 'action': 'propose-disclosure', 'style': 'mla'})
    assert proposed['proposal'].startswith('proposal_')
